function makeVariants(
  baseSku: string,
  sizes: string[],
  colors: { name: string; hex: string }[],
  defaultStock = 14
): ProductVariant[] {
  const list: ProductVariant[] = [];
  for (const color of colors) {
    for (const size of sizes) {
      const stock = size === 'XL' && color.name === colors[colors.length - 1].name ? 2 : defaultStock;
      list.push({
        id: `${baseSku}-${color.name.toUpperCase().replace(/\s+/g, '')}-${size}`,
        size,
        colorName: color.name,
        colorHex: color.hex,
        stock,
        sku: `${baseSku}-${color.name.slice(0, 3).toUpperCase()}-${size}`,
      });
    }
  }
  return list;
}

